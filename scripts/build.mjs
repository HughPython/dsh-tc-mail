#!/usr/bin/env node
/**
 * Build both halves of the plugin.
 *
 * Host   : ESM bundle  -> lib/index.js   (Node builtins stay external)
 * Client : CJS bundle  -> lib/client.js  wrapped in the Harness lazy-factory
 *          format `window.__ModuleLoader__.load({ id, factory })`.
 *
 * The client bundle must stay a plain side-effect script: `react` and
 * `react/jsx-runtime` resolve from the host's frozen module table through the
 * `require` argument the factory receives, so they are marked external.
 */

import { build, context } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(import.meta.dirname, '..')
const watch = process.argv.includes('--watch')
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

const common = {
  bundle: true,
  logLevel: 'info',
  legalComments: 'none',
  charset: 'utf8',
}

const hostOptions = {
  ...common,
  entryPoints: [path.join(root, 'src/host/index.js')],
  outfile: path.join(root, 'lib/index.js'),
  format: 'esm',
  platform: 'node',
  target: 'node20',
}

const clientOptions = {
  ...common,
  entryPoints: [path.join(root, 'src/client/index.jsx')],
  outfile: path.join(root, 'lib/client.js'),
  format: 'cjs',
  platform: 'browser',
  target: 'chrome120',
  jsx: 'automatic',
  loader: { '.css': 'text' },
  external: ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client'],
}

/** Wrap esbuild's CJS output in the Harness lazy-factory envelope. */
const wrapClient = {
  name: 'harness-module-loader',
  setup(pluginBuild) {
    pluginBuild.onEnd(async (result) => {
      if (result.errors.length) return
      const bundle = await readFile(clientOptions.outfile, 'utf8')
      const wrapped =
        `/* ${pkg.name} ${pkg.version} — generated by scripts/build.mjs, do not edit */\n` +
        `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {\n` +
        `var module = { exports: {} };\nvar exports = module.exports;\n` +
        bundle +
        `\nreturn module.exports;\n} });\n`
      await writeFile(clientOptions.outfile, wrapped, 'utf8')
      console.log(`[build] lib/client.js ${(wrapped.length / 1024).toFixed(1)} KiB`)
    })
  },
}

async function run() {
  await mkdir(path.join(root, 'lib'), { recursive: true })

  if (!watch) {
    await build(hostOptions)
    await build({ ...clientOptions, plugins: [wrapClient] })
    console.log('[build] lib/index.js + lib/client.js ready')
    return
  }

  const hostCtx = await context(hostOptions)
  const clientCtx = await context({ ...clientOptions, plugins: [wrapClient] })
  await hostCtx.watch()
  await clientCtx.watch()
  console.log('[watch] watching src/ …')
}

run().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
